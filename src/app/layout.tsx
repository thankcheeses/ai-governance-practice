export default function RootLayout({
  children,
}: Readonly<{ children: React.ReactNode }>) {
  return (
    <html
      lang="en"
      data-theme="light"
      data-palette={DEFAULT_PALETTE}
      suppressHydrationWarning
    >
      <body className="min-h-dvh antialiased">
        {/*
          Sets the theme before first paint so there is no flash of the wrong
          one. Two things about where it sits are load-bearing.

          It is the first child of <body>, not a child of <head>, which is
          where it used to be. React 19 treats <head> as a set of hoistable
          resources and reconciles that set during hydration; a script rendered
          into it takes part in the reconciliation. On a warm reload the
          browser's head no longer matches the one React expects — font
          preloads it has already consumed are gone — and the mismatch surfaced
          as React error #418. Measured on the Pages build, reloading a
          worker-controlled page: 4/10 on /terms/, 5/10 on /home/, 3/10 on
          /study/ before the move; 0/12 on each of five routes after it. The
          error was recoverable, so nothing rendered wrong, but it was an
          unexplained console error on a public site.

          It is a plain inline <script>, not `next/script`. `beforeInteractive`
          looks like the right tool and is not: in the App Router it emits a
          `self.__next_s.push(...)` record that the Next runtime executes once
          the framework bundle has loaded, which is after first paint. That was
          measured too — with it, a stored dark theme still painted light on
          the first frame. An inline script runs synchronously as the parser
          reaches it, before any paintable element below it exists.
        */}
        <script dangerouslySetInnerHTML={{ __html: THEME_INIT_SCRIPT }} />
        {/*
          Which of the three palettes to use, applied before first paint under
          exactly the same constraints as the theme — a plain inline script,
          inside <body>, nothing paintable above it.

          It sits after the theme script because that one has a test pinning it
          to the front of <body>, and one of them has to be second. Order
          between these two does not matter: they set different attributes and
          neither reads the other, so the first frame is correct either way.
        */}
        <script dangerouslySetInnerHTML={{ __html: PALETTE_INIT_SCRIPT }} />
        {/*
          Text size, text spacing and the motion preference, applied before
          first paint for the same reason as the theme and under the same
          constraints — a plain inline script, inside <body>, with nothing
          paintable above it.

          The stake is higher here than it is for the theme. A theme flash is
          unpleasant; a text-size flash shows the person who told the app they
          need larger text the small text, on every single load, in the moment
          they are trying to start reading. It is placed after the theme script
          only because one of them has to be second and the theme has a
          placement test pinning it to the front.
        */}
        <script dangerouslySetInnerHTML={{ __html: READING_INIT_SCRIPT }} />
        {/*
          Keeps a browser-translated page from crashing. It has to run before
          React hydrates, which is why it is an inline script here rather than
          an effect. See src/lib/translation-guard.ts.
        */}
        <script dangerouslySetInnerHTML={{ __html: TRANSLATION_GUARD_SCRIPT }} />
        {/*
          After the theme script, deliberately. Placed above it this failed
          theme-init-placement.test.ts: anything rendered before that script is
          a paintable element, and a stored dark preference would show light
          for a frame. Telemetry is the last thing that should cost a visible
          flash, so it sits here beside the other non-visual mount.
        */}
        <TelemetryBoot />
        <ServiceWorker />
        <ThemeProvider>
          <PaletteProvider>
            <ProgressProvider>{children}</ProgressProvider>
          </PaletteProvider>
        </ThemeProvider>
      </body>
    </html>
  );
}
